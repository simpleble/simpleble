package simplegoble_test

import (
	"bytes"
	"os"
	"path/filepath"
	"runtime"
	"sync"
	"testing"

	"github.com/simpleble/simplegoble"
	"github.com/simpleble/simplegoble/internal/bindings"
)

func TestConcurrentBundleExtraction(t *testing.T) {
	root := t.TempDir()
	files := []bindings.LibraryFile{
		{Name: "library", Data: []byte{0, 0x7f, 0x80, 0xff}},
		{Name: "dependency", Data: []byte("native dependency")},
	}
	var wg sync.WaitGroup
	for i := 0; i < 16; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			dir, err := bindings.ExtractLibraries(root, files)
			if err != nil {
				t.Error(err)
				return
			}
			for _, file := range files {
				data, err := os.ReadFile(filepath.Join(dir, file.Name))
				if err != nil || !bytes.Equal(data, file.Data) {
					t.Errorf("extracted %s differs: %v", file.Name, err)
				}
			}
		}()
	}
	wg.Wait()
	entries, err := os.ReadDir(root)
	if err != nil {
		t.Fatal(err)
	}
	if len(entries) != 1 {
		t.Fatalf("expected one complete cache directory, got %d", len(entries))
	}
	dir, err := bindings.ExtractLibraries(root, files)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "library"), []byte("substituted native code"), 0600); err != nil {
		t.Fatal(err)
	}
	if _, err := bindings.ExtractLibraries(root, files); err == nil {
		t.Fatal("accepted substituted cache contents")
	}
}

func TestPackagedLibraryLoads(t *testing.T) {
	if _, err := os.Stat(filepath.Join("..", "internal", "bindings", "native", runtime.GOOS+"_"+runtime.GOARCH)); err != nil {
		if os.IsNotExist(err) {
			t.Skip("native bundle is generated by packaging CI")
		}
		t.Fatal(err)
	}
	if version, err := simplegoble.Version(); err != nil || version == "" {
		t.Fatalf("bundled native call: version=%q, error=%v", version, err)
	}
}
