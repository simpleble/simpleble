#!/bin/bash
# Builds SimpleBLE for iOS devices and simulators into
# prebuilt/<flavor>/SimpleBLE.xcframework, with its headers in
# prebuilt/<flavor>/include. PLAIN=1 builds against SimpleBLE's PLAIN backend,
# for tests on the simulator, which has no Bluetooth.
set -euo pipefail

PACKAGE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
if [ -f "$PACKAGE_DIR/../simpleble/CMakeLists.txt" ]; then
  ROOT="$(cd "$PACKAGE_DIR/.." && pwd)"
else
  ROOT="$PACKAGE_DIR/native"
fi

if [ "${PLAIN:-0}" = "1" ]; then FLAVOR=plain; SIMPLEBLE_PLAIN=ON; else FLAVOR=release; SIMPLEBLE_PLAIN=OFF; fi
BUILD_DIR="$PACKAGE_DIR/build/ios-$FLAVOR"
GENERATOR="Unix Makefiles"
if command -v ninja > /dev/null; then GENERATOR=Ninja; fi
OUTPUT_DIR="$PACKAGE_DIR/prebuilt/$FLAVOR"

build() {
  local sdk=$1 arch=$2
  cmake -S "$ROOT/simpleble" -B "$BUILD_DIR/$sdk-$arch" -G "$GENERATOR" \
    -DCMAKE_BUILD_TYPE=Release -DBUILD_SHARED_LIBS=OFF -DSIMPLEBLE_PLAIN=$SIMPLEBLE_PLAIN \
    -DCMAKE_SYSTEM_NAME=iOS -DCMAKE_OSX_SYSROOT=$sdk -DCMAKE_OSX_ARCHITECTURES=$arch -DCMAKE_OSX_DEPLOYMENT_TARGET=15.8 > /dev/null
  cmake --build "$BUILD_DIR/$sdk-$arch" --parallel > /dev/null
}

build iphoneos arm64
build iphonesimulator arm64
build iphonesimulator x86_64

mkdir -p "$BUILD_DIR/simulator"
lipo -create "$BUILD_DIR/iphonesimulator-arm64/lib/libsimpleble.a" "$BUILD_DIR/iphonesimulator-x86_64/lib/libsimpleble.a" \
  -output "$BUILD_DIR/simulator/libsimpleble.a"

rm -rf "$OUTPUT_DIR"
mkdir -p "$OUTPUT_DIR"
xcodebuild -create-xcframework \
  -library "$BUILD_DIR/iphoneos-arm64/lib/libsimpleble.a" \
  -library "$BUILD_DIR/simulator/libsimpleble.a" \
  -output "$OUTPUT_DIR/SimpleBLE.xcframework" > /dev/null

# NOTE: export.h is generated by the build, and is the same for every slice.
# SimpleBLE's public headers also include the kvn headers.
cp -R "$ROOT/simpleble/include" "$OUTPUT_DIR/include"
cp -R "$ROOT/dependencies/external/kvn" "$OUTPUT_DIR/include/kvn"
cp "$BUILD_DIR/iphoneos-arm64/export/simpleble/export.h" "$OUTPUT_DIR/include/simpleble/"
echo "Built $OUTPUT_DIR/SimpleBLE.xcframework"
