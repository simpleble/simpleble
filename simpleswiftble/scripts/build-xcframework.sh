#!/bin/bash
# Builds SimpleCBLE, with SimpleBLE, into build/<flavor>/CSimpleBLE.xcframework for the root Package.swift, with
# slices for macOS, iOS, the iOS simulator and Mac Catalyst.
# PLAIN=1 builds against SimpleBLE's PLAIN backend, for tests without Bluetooth hardware.
set -euo pipefail

PACKAGE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ROOT="$(cd "$PACKAGE_DIR/.." && pwd)"

if [ "${PLAIN:-0}" = "1" ]; then FLAVOR=plain; SIMPLEBLE_PLAIN=ON; else FLAVOR=release; SIMPLEBLE_PLAIN=OFF; fi
BUILD_DIR="$PACKAGE_DIR/build/$FLAVOR"
GENERATOR="Unix Makefiles"
if command -v ninja > /dev/null; then GENERATOR=Ninja; fi

# Builds one slice and merges SimpleCBLE and SimpleBLE into a single static library.
build() {
  local slice=$1; shift
  local dir="$BUILD_DIR/cmake/$slice"
  cmake -S "$ROOT/simplecble" -B "$dir" -G "$GENERATOR" -DCMAKE_BUILD_TYPE=Release -DBUILD_SHARED_LIBS=OFF \
    -DSIMPLEBLE_PLAIN=$SIMPLEBLE_PLAIN -DCMAKE_INSTALL_PREFIX="$dir/install" "$@" > /dev/null
  cmake --build "$dir" --parallel > /dev/null
  cmake --install "$dir" > /dev/null
  libtool -static -no_warning_for_no_symbols -o "$dir/libCSimpleBLE.a" \
    "$dir/install/lib/libsimplecble.a" "$dir/install/lib/libsimpleble.a"
}

build macos -DCMAKE_OSX_ARCHITECTURES="arm64;x86_64" -DCMAKE_OSX_DEPLOYMENT_TARGET=15.0
build ios -DCMAKE_SYSTEM_NAME=iOS -DCMAKE_OSX_SYSROOT=iphoneos -DCMAKE_OSX_ARCHITECTURES=arm64 \
  -DCMAKE_OSX_DEPLOYMENT_TARGET=15.8
build iossimulator -DCMAKE_SYSTEM_NAME=iOS -DCMAKE_OSX_SYSROOT=iphonesimulator \
  -DCMAKE_OSX_ARCHITECTURES="arm64;x86_64" -DCMAKE_OSX_DEPLOYMENT_TARGET=15.8

# NOTE: Mac Catalyst is selected by the compiler target, which names one architecture, so each is built on its own.
for arch in arm64 x86_64; do
  build maccatalyst-$arch -DCMAKE_SYSTEM_NAME=Darwin -DCMAKE_OSX_SYSROOT=macosx -DCMAKE_OSX_ARCHITECTURES=$arch \
    -DCMAKE_C_COMPILER_TARGET=$arch-apple-ios15.8-macabi -DCMAKE_CXX_COMPILER_TARGET=$arch-apple-ios15.8-macabi
done
mkdir -p "$BUILD_DIR/cmake/maccatalyst"
lipo -create "$BUILD_DIR/cmake/maccatalyst-arm64/libCSimpleBLE.a" "$BUILD_DIR/cmake/maccatalyst-x86_64/libCSimpleBLE.a" \
  -output "$BUILD_DIR/cmake/maccatalyst/libCSimpleBLE.a"

# NOTE: export.h is generated by the build, and is the same for every slice.
HEADERS_DIR="$BUILD_DIR/include"
rm -rf "$HEADERS_DIR"
mkdir -p "$HEADERS_DIR"
cp -R "$BUILD_DIR/cmake/macos/install/include/simplecble" "$HEADERS_DIR/"
cat > "$HEADERS_DIR/module.modulemap" << 'EOF'
module CSimpleBLE {
    umbrella header "simplecble/simplecble.h"
    link "c++"
    export *
}
EOF

rm -rf "$BUILD_DIR/CSimpleBLE.xcframework"
xcodebuild -create-xcframework \
  -library "$BUILD_DIR/cmake/macos/libCSimpleBLE.a" -headers "$HEADERS_DIR" \
  -library "$BUILD_DIR/cmake/ios/libCSimpleBLE.a" -headers "$HEADERS_DIR" \
  -library "$BUILD_DIR/cmake/iossimulator/libCSimpleBLE.a" -headers "$HEADERS_DIR" \
  -library "$BUILD_DIR/cmake/maccatalyst/libCSimpleBLE.a" -headers "$HEADERS_DIR" \
  -output "$BUILD_DIR/CSimpleBLE.xcframework" > /dev/null
echo "Built $BUILD_DIR/CSimpleBLE.xcframework"
