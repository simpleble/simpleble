// Generates lib/src/internal/bindings.g.dart from the SimpleCBLE and
// SimpleDartBLE headers. Run it from simpledartble/ after changing either:
//
//   dart run tool/ffigen.dart
import 'dart:io';

import 'package:ffigen/ffigen.dart';

const _headers = ['../simplecble/include/simplecble/simplecble.h', 'native/include/simpledartble/simpledartble.h'];

Future<void> main() async {
  final package = Platform.script.resolve('../');

  // NOTE: CMake generates SimpleCBLE's export header. Its macro only marks
  // exported symbols, so an empty one parses the same declarations.
  final generated = Directory.systemTemp.createTempSync('simpledartble_ffigen');
  File('${generated.path}/simplecble/export.h')
    ..createSync(recursive: true)
    ..writeAsStringSync('#define SIMPLECBLE_EXPORT\n');

  // NOTE: lib/src/internal/advanced.dart declares the platform functions, as each platform's header only has its own.
  bool platform(String name) => RegExp(r'^simpleble_advanced_(android|ios|linux|macos)_').hasMatch(name);
  bool ours(String name) => (name.startsWith('simpleble_') || name.startsWith('simpledartble_')) && !platform(name);

  try {
    await FfiGenerator(
      input: Input(
        entryPoints: [for (final header in _headers) package.resolve(header)],
        compilerOptions: [
          '-I${package.resolve('../simplecble/include').toFilePath()}',
          '-I${package.resolve('native/include').toFilePath()}',
          '-I${generated.path}',
        ],
        appendCompilerOptions: true,
      ),
      output: Output(
        dart: DartOutput(path: package.resolve('lib/src/internal/bindings.g.dart')),
        style: const NativeExternalBindings(assetId: 'package:simpledartble/simpledartble.dart'),
        preamble:
            '// Generated by tool/ffigen.dart from the SimpleCBLE headers. Do not edit.\n'
            '// ignore_for_file: type=lint',
      ),
      visitors: [
        Visitor(
          func: (node) => node.isIncluded = ours(node.originalName),
          struct: (node) => node.isIncluded = ours(node.originalName),
          // NOTE: SimpleCBLE's enums are int-sized with every compiler it supports.
          enumClass: (node) {
            node.isIncluded = ours(node.originalName);
            node.silenceWarning = true;
          },
        ),
      ],
    ).generate();
  } finally {
    generated.deleteSync(recursive: true);
  }
}
